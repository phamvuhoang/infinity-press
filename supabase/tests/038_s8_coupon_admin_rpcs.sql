begin;
select plan(21);

-- S8: the admin coupon RPCs (spec 7.2).

-- Fixtures: an admin profile with a public.user_roles row, a plain reader, one book, and one
-- coupon created directly (not through the RPC) so the non-admin negative cases below have a real
-- id to call against.
insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at, raw_app_meta_data, raw_user_meta_data, created_at, updated_at)
values
  ('00000000-0000-0000-0000-000000000000', 'c9000000-0000-0000-0000-0000000000a1', 'authenticated', 'authenticated', 's8-admin-rpc-admin@example.test', '', now(), '{}'::jsonb, '{}'::jsonb, now(), now()),
  ('00000000-0000-0000-0000-000000000000', 'c9000000-0000-0000-0000-0000000000a2', 'authenticated', 'authenticated', 's8-admin-rpc-reader@example.test', '', now(), '{}'::jsonb, '{}'::jsonb, now(), now());
insert into public.user_roles (profile_id, role)
select id, 'admin' from public.profiles where auth_user_id = 'c9000000-0000-0000-0000-0000000000a1';

insert into public.authors (id, canonical_slug, display_name)
values ('c9000000-0000-0000-0000-0000000000b1', 's8-admin-rpc-author', 'S8 Admin RPC Author');
insert into public.books (id, canonical_key, original_language, primary_author_id)
values ('c9000000-0000-0000-0000-0000000000b2', 's8-admin-rpc-book', 'vi', 'c9000000-0000-0000-0000-0000000000b1');

insert into public.coupons (id, code, kind, percent_off, active)
values ('c9000000-0000-0000-0000-000000000001', 'FIXTURE', 'percent', 10, true);

create temporary table t_profiles as
select
  (select id from public.profiles where auth_user_id = 'c9000000-0000-0000-0000-0000000000a1') as admin_id,
  (select id from public.profiles where auth_user_id = 'c9000000-0000-0000-0000-0000000000a2') as reader_id;
grant select on t_profiles to public;

-- Holds the id admin_create_coupon returns for TESTER-100, since that id is generated by
-- gen_random_uuid() inside the function and cannot be hardcoded.
create temporary table t_coupons (label text primary key, id uuid);
grant select, insert on t_coupons to public;

-- (1)-(2) Grants: anon holds no EXECUTE on the admin surface at all.
select is(
  has_function_privilege('anon', 'public.admin_list_coupons()', 'EXECUTE'),
  false,
  'anon holds no EXECUTE on admin_list_coupons'
);
select is(
  has_function_privilege('anon', 'public.admin_create_coupon(text, text, int, bigint, text, timestamptz, timestamptz, int, int, text, uuid[], uuid[])', 'EXECUTE'),
  false,
  'anon holds no EXECUTE on admin_create_coupon'
);

-- As the plain reader. (3)-(6)
set local role authenticated;
select set_config('request.jwt.claim.sub', 'c9000000-0000-0000-0000-0000000000a2', true);
select throws_ok(
  $$select public.admin_list_coupons()$$,
  '42501', null, 'a signed-in reader cannot list coupons');
select throws_ok(
  $$select public.admin_get_coupon('c9000000-0000-0000-0000-000000000001')$$,
  '42501', null, 'a signed-in reader cannot fetch one coupon');
select throws_ok(
  $$select public.admin_create_coupon('SNEAKY', 'percent', 50, null, null, null, null, null, 1, null, '{}'::uuid[], '{}'::uuid[])$$,
  '42501', null, 'a signed-in reader cannot create a coupon');
select throws_ok(
  $$select public.admin_update_coupon('c9000000-0000-0000-0000-000000000001', 'percent', 50, null, null, null, null, false, null, 1, null, '{}'::uuid[], '{}'::uuid[])$$,
  '42501', null, 'a signed-in reader cannot change a coupon');

-- As the admin. (7)-(11)
set local role authenticated;
select set_config('request.jwt.claim.sub', 'c9000000-0000-0000-0000-0000000000a1', true);

insert into t_coupons (label, id)
select 'tester', public.admin_create_coupon('  tester-100 ', 'percent', 100, null, null, null, null, null, 1, 'launch testers', '{}'::uuid[], '{}'::uuid[]);

select is(
  (select l.code from public.admin_list_coupons() l where l.id = (select id from t_coupons where label = 'tester')),
  'TESTER-100', 'a pasted code is normalized on creation');
select throws_ok(
  $$select public.admin_create_coupon('no', 'percent', 50, null, null, null, null, null, 1, null, '{}'::uuid[], '{}'::uuid[])$$,
  '22023', null, 'a code too short to type is refused');
select is(
  (select count(*) from public.audit_logs a where a.action = 'coupon.created'),
  1::bigint, 'creating a coupon writes one audit row');
select is(
  (select l.reserved_count from public.admin_list_coupons() l where l.code = 'TESTER-100'),
  0::bigint, 'a new coupon has no reservations');

-- Book scope round-trips through the list.
select public.admin_create_coupon('SCOPED', 'percent', 20, null, null, null, null, null, 1, null, array['c9000000-0000-0000-0000-0000000000b2']::uuid[], '{}'::uuid[]);
select is(
  (select array_length(l.book_ids, 1) from public.admin_list_coupons() l where l.code = 'SCOPED'),
  1, 'the book scope comes back on the list');

-- admin_get_coupon must not read through admin_list_coupons's own `limit 200` (controller ruling
-- P3): a coupon older than the 200 newest must still be fetchable by id even though the capped
-- list no longer shows it. (12)-(13)
reset role;
insert into public.coupons (id, code, kind, percent_off, created_at)
values ('c9000000-0000-0000-0000-0000000000e1', 'OLDONE', 'percent', 10, now() - interval '1000 days');
insert into public.coupons (code, kind, percent_off, created_at)
select 'FILLER' || g::text, 'percent', 10, now() - (g || ' seconds')::interval
from generate_series(1, 200) g;

set local role authenticated;
select set_config('request.jwt.claim.sub', 'c9000000-0000-0000-0000-0000000000a1', true);
select is(
  (select c.code from public.admin_get_coupon('c9000000-0000-0000-0000-0000000000e1') c),
  'OLDONE', 'admin_get_coupon finds a coupon outside the capped list''s 200-row window');
select is(
  (select count(*) from public.admin_list_coupons() l where l.code = 'OLDONE'),
  0::bigint, 'that same coupon is excluded from the capped list, confirming the scenario');

-- Value immutability once reserved: an order for the reader and a reserved coupon_redemptions row
-- against TESTER-100.
reset role;
insert into public.orders (id, profile_id, status, payment_status, market_code, currency, total_minor, subtotal_minor, payment_provider)
values ('c9000000-0000-0000-0000-0000000000d1', (select reader_id from t_profiles), 'pending', 'pending', 'VN', 'VND', 100000, 100000, 'simulator');
insert into public.coupon_redemptions (coupon_id, order_id, profile_id, discount_minor, status)
values ((select id from t_coupons where label = 'tester'), 'c9000000-0000-0000-0000-0000000000d1', (select reader_id from t_profiles), 100000, 'reserved');

set local role authenticated;
select set_config('request.jwt.claim.sub', 'c9000000-0000-0000-0000-0000000000a1', true);

-- (14)-(17)
select throws_ok(
  format($$select public.admin_update_coupon(%L, 'percent', 50, null, null, null, null, true, null, 1, null, '{}'::uuid[], '{}'::uuid[])$$, (select id from t_coupons where label = 'tester')),
  'EB025', null, 'the value of a reserved coupon cannot change');
select throws_ok(
  format($$select public.admin_update_coupon(%L, 'fixed', null, 5000, 'VND', null, null, true, null, 1, null, '{}'::uuid[], '{}'::uuid[])$$, (select id from t_coupons where label = 'tester')),
  'EB025', null, 'changing the kind of a reserved coupon is also locked');
select lives_ok(
  format($$select public.admin_update_coupon(%L, 'percent', 100, null, null, null, now() + interval '1 day', false, null, 1, null, '{}'::uuid[], '{}'::uuid[])$$, (select id from t_coupons where label = 'tester')),
  'a reserved coupon can still be deactivated and have its window changed');
select is(
  (select g.active from public.admin_get_coupon((select id from t_coupons where label = 'tester')) g),
  false, 'deactivation took effect');

-- (18)-(21) The update path is audited too, symmetrically with the create path's test 9, and the
-- row names the coupon and carries the value fields (fix round 1) - not merely that an update
-- happened.
select is(
  (select count(*) from public.audit_logs a where a.action = 'coupon.updated'),
  1::bigint, 'updating a coupon writes one audit row');
select is(
  (select a.entity_id from public.audit_logs a where a.action = 'coupon.updated'),
  (select id from t_coupons where label = 'tester'),
  'the update audit row names the coupon');
select is(
  (select a.metadata ->> 'kind_to' from public.audit_logs a where a.action = 'coupon.updated'),
  'percent', 'the update audit row records the applied kind');
select is(
  ((select a.metadata ->> 'percent_off_to' from public.audit_logs a where a.action = 'coupon.updated'))::int,
  100, 'the update audit row records the applied value');

reset role;
select * from finish();
rollback;
